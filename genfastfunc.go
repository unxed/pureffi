func emitInterleavedFloat32x1(buf *bytes.Buffer) {
	type caseData struct {
		FloatPos int
		Params   string
		NumInts  int
	}
	type totalData struct {
		TotalArgs int
		Cases     []caseData
	}
	var groups []totalData
	for totalArgs := 2; totalArgs <= 15; totalArgs++ {
		var cases []caseData
		for floatPos := 0; floatPos <= totalArgs-2; floatPos++ {
			var parts []string
			intIdx := 1
			for i := 0; i < totalArgs; i++ {
				if i == floatPos {
					parts = append(parts, "f1 float32")
				} else {
					parts = append(parts, fmt.Sprintf("a%d uintptr", intIdx))
					intIdx++
				}
			}
			cases = append(cases, caseData{
				FloatPos: floatPos,
				Params:   strings.Join(parts, ", "),
				NumInts:  totalArgs - 1,
			})
		}
		groups = append(groups, totalData{TotalArgs: totalArgs, Cases: cases})
	}
	execTemplate(buf, "interleaved", tmplInterleavedFloat, groups)
}

var tmplTryRegisterFastPath = `func tryRegisterFastPath(fn reflect.Value, cif *types.CallInterface, cfn uintptr, ty reflect.Type) bool {
	if !((runtime.GOARCH == "amd64" || runtime.GOARCH == "arm64") && runtime.GOOS != "windows") {
		return false
	}
	numIn := ty.NumIn()
	if numIn > 15 {
		return false
	}

	var numFloats, numInts int
	trailingFloats := true
	seenFloat := false
	floatPos := -1

	for i := 0; i < numIn; i++ {
		switch ty.In(i).Kind() {
		case reflect.Uintptr, reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
			reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
			reflect.Bool, reflect.Pointer, reflect.UnsafePointer:
			if seenFloat {
				trailingFloats = false
			}
			numInts++
		case reflect.Float32, reflect.Float64:
			if !seenFloat {
				floatPos = i
			}
			seenFloat = true
			numFloats++
		default:
			return false // Fallback for Structs, Arrays, Strings, Slices
		}
	}
	if numFloats > 8 || numInts > 15 {
		return false
	}

	hasReturn := ty.NumOut() > 0
	if hasReturn {
		switch ty.Out(0).Kind() {
		case reflect.Uintptr, reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
			reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
			reflect.Bool, reflect.Pointer, reflect.UnsafePointer:
		case reflect.Float32, reflect.Float64:
			return false // Fast wrappers return uintptr, which uses a different ABI register class.
		default:
			return false
		}
	}

	if numFloats == 0 {
		registerFastFunc(fn, cif, cfn, numInts, hasReturn)
		return true
	}
	if numFloats == 1 && trailingFloats && ty.In(numInts).Kind() == reflect.Float32 {
		registerFastFuncFloat32x1(fn, cif, cfn, numInts, hasReturn)
		return true
	}
	if numFloats == 1 && trailingFloats && ty.In(numInts).Kind() == reflect.Float64 {
		registerFastFuncFloat64x1(fn, cif, cfn, numInts, hasReturn)
		return true
	}
	if numFloats == 1 && !trailingFloats && ty.In(floatPos).Kind() == reflect.Float32 {
		registerFastFuncInterleavedFloat32x1(fn, cif, cfn, numIn, floatPos, hasReturn)
		return true
	}

	return false
}
`
