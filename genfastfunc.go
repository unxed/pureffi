type fastPattern struct {
	Name      string
	MinInts   int
	MaxInts   int
	NumFloats int
	FloatBits int
	Layout    string
}

var patterns = []fastPattern{
	{Name: "IntOnly", MaxInts: 15, NumFloats: 0},
	{Name: "TrailingFloat32x1", MaxInts: 15, NumFloats: 1, FloatBits: 32, Layout: "trailing"},
	{Name: "TrailingFloat64x1", MaxInts: 15, NumFloats: 1, FloatBits: 64, Layout: "trailing"},
	{Name: "InterleavedFloat32x1", MinInts: 1, MaxInts: 15, NumFloats: 1, FloatBits: 32, Layout: "interleaved"},
}

func main() {
	var buf bytes.Buffer
	execTemplate(&buf, "header", tmplHeader, nil)
	emitIntOnly(&buf)
	emitTrailingFloat(&buf, 32)
	emitTrailingFloat(&buf, 64)
	emitInterleavedFloat32x1(&buf)
	execTemplate(&buf, "tryRegister", tmplTryRegisterFastPath, nil)

	src, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatalf("gofmt: %v\n%s", err, buf.String())
	}
	if err := os.WriteFile("zz_fast_func.go", src, 0644); err != nil {
		log.Fatal(err)
	}
}

var funcs = template.FuncMap{
	"seq": func(n int) []int {
		s := make([]int, n)
		for i := range s {
			s[i] = i
		}
		return s
	},
	"add": func(a, b int) int { return a + b },
	"argList": func(n int) string {
		if n == 0 {
			return ""
		}
		var parts []string
		for i := 0; i < n; i++ {
			parts = append(parts, fmt.Sprintf("a%d uintptr", i+1))
		}
		return strings.Join(parts, ", ")
	},
}

func execTemplate(buf *bytes.Buffer, name, text string, data any) {
	t := template.Must(template.New(name).Funcs(funcs).Parse(text))
	if err := t.Execute(buf, data); err != nil {
		log.Fatalf("template %s: %v", name, err)
	}
}

